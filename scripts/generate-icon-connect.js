#!/usr/bin/env node
/**
 * generate-icon-connect.js
 * Reads every icon set on the Figma "Icon" page and writes Code Connect
 * mappings to @mui/icons-material, so Dev Mode shows `<ArrowBackRounded />`
 * instead of an anonymous instance.
 *
 * The Figma library is Google Material Icons, the same source as MUI, so the
 * names line up: `arrow-back` + Style=rounded → `ArrowBackRounded`.
 * Anything without an exact MUI match for all five styles is skipped and
 * reported — never guessed.
 *
 * Usage: npm run icons:connect     (needs FIGMA_ACCESS_TOKEN with File content: Read)
 * Then:  npm run code-connect:dry-run
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'code-connect', 'icons');
const MUI_DIR = path.join(ROOT, 'node_modules', '@mui', 'icons-material');
// Icons the DS ships itself (npm run icons:custom) for sets MUI doesn't have.
const CUSTOM_DIR = path.join(ROOT, 'code', 'core', 'icons');

const FILE_KEY = 'XgxprkSY5mGbzIIwlmscCt';
const FILE_SLUG = 'Cariva-Core-Design-System';
const ICON_PAGE_ID = '3616:1454';
// Medical icon library — single-style components the DS ships in code/core/icons/.
const MEDICAL_SECTION_ID = '5406:35089';

// Figma `Style` variant value → MUI export suffix.
const STYLES = {
  filled: '',
  outlined: 'Outlined',
  rounded: 'Rounded',
  sharp: 'Sharp',
  'two-tone': 'TwoTone',
};

// Figma names that differ from MUI's. Each one is verified, not guessed:
// - MUI spells a leading digit as a word.
// - chevron-up/down: Material calls these expand_less/expand_more. Paths
//   compared 2026-09-11 — identical in both filled and rounded styles.
const NAME_ALIASES = {
  '3d-rotation': 'ThreeDRotation',
  '4k': 'FourK',
  '360': 'ThreeSixty',
  'chevron-up': 'ExpandLess',
  'chevron-down': 'ExpandMore',
};

function loadToken() {
  if (process.env.FIGMA_ACCESS_TOKEN) return process.env.FIGMA_ACCESS_TOKEN;
  for (const file of ['.env.local', '.env']) {
    const p = path.join(ROOT, file);
    if (!fs.existsSync(p)) continue;
    const line = fs.readFileSync(p, 'utf8').split('\n').find((l) => l.startsWith('FIGMA_ACCESS_TOKEN='));
    if (line) return line.slice('FIGMA_ACCESS_TOKEN='.length).trim();
  }
  console.error('✖ Missing FIGMA_ACCESS_TOKEN — add it to .env.local (scope: File content → Read).');
  process.exit(1);
}

function toMuiBase(figmaName) {
  const name = figmaName.replace(/^crv-icon-/, '');
  if (NAME_ALIASES[name]) return NAME_ALIASES[name];
  return name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

const muiExists = (exportName) => fs.existsSync(path.join(MUI_DIR, `${exportName}.js`));
const customExports = (base) => {
  const file = path.join(CUSTOM_DIR, `${base}.tsx`);
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
};
const customExists = (base, exportName) => customExports(base).includes(`export const ${exportName} =`);

const res = await fetch(
  `https://api.figma.com/v1/files/${FILE_KEY}/nodes?ids=${encodeURIComponent(ICON_PAGE_ID)}&depth=2`,
  { headers: { 'X-Figma-Token': loadToken() } },
);
if (!res.ok) {
  console.error(`✖ Figma API ${res.status}: ${await res.text()}`);
  process.exit(1);
}
const page = (await res.json()).nodes[ICON_PAGE_ID].document;

// Icon sets live one level down, inside the category frames (action, alert, av, …).
const sets = page.children
  .filter((n) => n.type === 'FRAME')
  .flatMap((frame) => frame.children ?? [])
  .filter((n) => n.type === 'COMPONENT_SET')
  .sort((a, b) => a.name.localeCompare(b.name));

const mapped = [];
const skipped = [];
const seen = new Map();

for (const set of sets) {
  const base = toMuiBase(set.name);
  const inMui = Object.values(STYLES).every((suffix) => muiExists(base + suffix));
  const inDs = !inMui && Object.values(STYLES).every((suffix) => customExists(base, base + suffix));
  if (!inMui && !inDs) {
    skipped.push({ name: set.name, id: set.id, reason: `no @mui/icons-material/${base} and no code/core/icons/${base}.tsx` });
    continue;
  }
  if (seen.has(base)) {
    skipped.push({ name: set.name, id: set.id, reason: `duplicate of "${seen.get(base)}" (both map to ${base})` });
    continue;
  }
  seen.set(base, set.name);
  mapped.push({ name: set.name, id: set.id, base, source: inMui ? 'mui' : 'ds' });
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const HEADER = `// AUTO-GENERATED by scripts/generate-icon-connect.js — do not edit.
// Regenerate: npm run icons:connect
`;

for (const [style, suffix] of Object.entries(STYLES)) {
  const imports = mapped.map(({ base, source }) =>
    source === 'mui'
      ? `import ${base + suffix} from '@mui/icons-material/${base + suffix}';`
      : `import { ${base + suffix} } from '../../code/core/icons/${base}';`,
  );
  const connects = mapped.map(({ name, id, base }) => {
    const exp = base + suffix;
    const url = `https://www.figma.com/design/${FILE_KEY}/${FILE_SLUG}?node-id=${id.replace(':', '-')}`;
    return `// ${name}
figma.connect(${exp}, '${url}', {
  variant: { Style: '${style}' },
  example: () => <${exp} />,
});`;
  });
  const body = `${HEADER}import figma from '@figma/code-connect';
${imports.join('\n')}

${connects.join('\n\n')}
`;
  fs.writeFileSync(path.join(OUT_DIR, `icons-${style}.figma.tsx`), body, 'utf8');
}

// Medical section: each component maps to the one DS export of the same name.
const medicalRes = await fetch(
  `https://api.figma.com/v1/files/${FILE_KEY}/nodes?ids=${encodeURIComponent(MEDICAL_SECTION_ID)}&depth=2`,
  { headers: { 'X-Figma-Token': loadToken() } },
);
if (!medicalRes.ok) {
  console.error(`✖ Figma API ${medicalRes.status}: ${await medicalRes.text()}`);
  process.exit(1);
}
const medicalIcons = (await medicalRes.json()).nodes[MEDICAL_SECTION_ID].document.children
  .filter((n) => n.type === 'SECTION')
  .flatMap((group) => (group.children ?? []).filter((n) => n.type === 'COMPONENT'))
  .sort((a, b) => a.name.localeCompare(b.name));
const medicalMapped = [];
for (const icon of medicalIcons) {
  const base = toMuiBase(icon.name);
  if (customExists(base, base)) medicalMapped.push({ name: icon.name, id: icon.id, base });
  else skipped.push({ name: icon.name, id: icon.id, reason: `no code/core/icons/${base}.tsx — run npm run icons:custom` });
}
fs.writeFileSync(
  path.join(OUT_DIR, 'icons-medical.figma.tsx'),
  `${HEADER}import figma from '@figma/code-connect';
${medicalMapped.map(({ base }) => `import { ${base} } from '../../code/core/icons/${base}';`).join('\n')}

${medicalMapped
  .map(({ name, id, base }) => {
    const url = `https://www.figma.com/design/${FILE_KEY}/${FILE_SLUG}?node-id=${id.replace(':', '-')}`;
    return `// ${name}
figma.connect(${base}, '${url}', {
  example: () => <${base} />,
});`;
  })
  .join('\n\n')}
`,
  'utf8',
);

const report = `# Icon Code Connect

Generated by \`npm run icons:connect\` from the Figma **Icon** page. Do not edit the \`.figma.tsx\` files by hand.

- **${mapped.filter((m) => m.source === 'mui').length}** of ${sets.length} icon sets mapped to \`@mui/icons-material\`, × 5 styles each
- **${mapped.filter((m) => m.source === 'ds').length}** mapped to icons the DS ships itself in \`code/core/icons/\` (\`npm run icons:custom\`): ${mapped.filter((m) => m.source === 'ds').map((m) => `\`${m.name}\``).join(', ')}
- **${medicalMapped.length}** of ${medicalIcons.length} Medical icons mapped to \`code/core/icons/\` (single style, \`icons-medical.figma.tsx\`)
- **${skipped.length}** skipped — no exact MUI match, so Dev Mode shows them unmapped rather than wrong

| Figma set | Node | Why skipped |
|---|---|---|
${skipped.map((s) => `| \`${s.name}\` | \`${s.id}\` | ${s.reason} |`).join('\n')}
`;
fs.writeFileSync(path.join(OUT_DIR, 'README.md'), report, 'utf8');

console.log(`✅ Mapped ${mapped.length}/${sets.length} icon sets × ${Object.keys(STYLES).length} styles → ${path.relative(ROOT, OUT_DIR)}/ (${mapped.filter((m) => m.source === 'ds').length} from code/core/icons)`);
console.log(`✅ Mapped ${medicalMapped.length}/${medicalIcons.length} Medical icons → icons-medical.figma.tsx`);
console.log(`   Skipped ${skipped.length}: ${skipped.map((s) => s.name).join(', ')}`);
